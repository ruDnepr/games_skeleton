/// История партии для отмены хода.
///
/// В офлайн-режимах (против компьютера и вдвоём на одном устройстве) отмена
/// всегда доступна и возвращается на начало прошлого хода. В сети отмена идёт
/// по согласию: одна сторона спрашивает, вторая подтверждает — и тогда оба
/// откатываются к снимку. Поэтому снимок — это полное состояние, а не патч.
library;

import 'model.dart';

/// Стек прошлых состояний с удобным «откатить один ход».
class GameHistory {
  GameHistory();

  final List<GameState> _stack = [];

  /// Есть ли что отменить.
  bool get canUndo => _stack.isNotEmpty;

  /// Число сохранённых снимков — для отладки и тестов.
  int get length => _stack.length;

  /// Запоминает состояние перед ходом.
  void push(GameState state) => _stack.add(state);

  /// Возвращает состояние до последнего хода и убирает его из стека.
  /// Бросает [StateError], если стек пуст.
  GameState pop() {
    if (_stack.isEmpty) {
      throw StateError('Отменять нечего');
    }
    return _stack.removeLast();
  }

  /// Очищает историю — например, при начале новой партии.
  void clear() => _stack.clear();
}
